def get_image_size(ratio: str = "3:4") -> str:
    """
    根据输出比例获取 DashScope 图像生成尺寸字符串。

    Args:
        ratio: 输出比例，如 "3:4"、"1:1"、"4:3"、"16:9"

    Returns:
        尺寸字符串（如 "768*1024"）；未知比例回退到默认 3:4 竖图。
    """
    return IMAGE_SIZES.get(ratio, DEFAULT_IMAGE_SIZE)
